local function cloud(x, y, big)
  local w = big and 3 or 1
  for i = 0, w - 1 do
    circfill(x + i * 12, y, 7, C.WHITE)
    circfill(x + i * 12 - 4, y + 3, 5, C.WHITE)
    circfill(x + i * 12 + 4, y + 3, 5, C.WHITE)
  end
