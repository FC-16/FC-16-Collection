local function mario_tile_collide(m)
  local hw = (m.big > 0 and not m.crouch) and 6 or 5
  local h = (m.big > 0 and not m.crouch) and 30 or 15
  -- 水平
  m.x = m.x + m.vx
  local dir = m.vx > 0 and 1 or -1
  if m.vx ~= 0 then
    local edge = m.x + dir * hw
    for _, oy in ipairs({ 2, h / 2, h - 2 }) do
      if solid_px(edge, m.y + oy) then
        local tx = flr(edge / 16)
        m.x = dir == 1 and tx * 16 - hw or (tx + 1) * 16 + hw
        m.vx = 0
        break
      end
    end
  end
  -- 左界：不得越过镜头左缘
  if m.x < game.cam + hw then m.x = game.cam + hw if m.vx < 0 then m.vx = 0 end end
  -- 垂直
  m.y = m.y + m.vy
  m.on_ground = false
  if m.vy >= 0 then
    local fy = m.y + h
    if solid_px(m.x - hw + 1, fy) or solid_px(m.x + hw - 1, fy) then
      m.y = flr(fy / 16) * 16 - h
      m.vy = 0
      m.on_ground = true
      game.chain = 0
    end
  else
    local ty = flr(m.y / 16)
    local lx, rx = flr((m.x - hw + 1) / 16), flr((m.x + hw - 1) / 16)
    local lhit = solid_or_hidden(lx, ty, true)
    local rhit = solid_or_hidden(rx, ty, true)
    if lhit or rhit then
      -- 选重叠更多的那列顶块
      local tx
      if lhit and rhit then
        tx = ((m.x - hw + 1) % 16 > 15 - (m.x + hw - 1) % 16) and lx or rx
      else
        tx = lhit and lx or rx
      end
      m.y = (ty + 1) * 16
      m.vy = 0
      bump_block(tx, ty)
    end
  end
  -- 站台（升降平台）
  m.on_plat = nil
  for _, e in ipairs(game.ents) do
    if e.kind == "plat" then
      local top = e.y
      if m.vy >= 0 and m.x + hw - 2 > e.x - 24 and m.x - hw + 2 < e.x + 24
        and m.y + h >= top - 1 and m.y + h <= top + 8 then
        m.y = top - h
        m.vy = 0
        m.on_ground = true
        m.on_plat = e
        game.chain = 0
      end
    end
  end
  -- 走出地面转为下落
  if m.on_ground and m.vy == 0 and not m.on_plat then
    if not (solid_px(m.x - hw + 1, m.y + h + 2) or solid_px(m.x + hw - 1, m.y + h + 2)) then
      m.on_ground = false
      m.jumping = false
      m.jgroup = jump_group(m.vx)
    end
  end
end

local function update_mario()
  local m = game.mario
  local press = (btn(KEY.R) and 1 or 0) - (btn(KEY.L) and 1 or 0)
  if m.big > 0 then
    m.crouch = m.on_ground and btn(KEY.D)
  end
  local run = btn(KEY.B)
  if run and press ~= 0 and press == (m.vx == 0 and press or sgn(m.vx)) then
    m.grace = RUN_GRACE
  elseif m.grace and m.grace > 0 then
    m.grace = m.grace - 1
  end
  -- 水平物理（换算表见文件头）
  if m.on_ground then
    if press ~= 0 then
      if m.vx * press < -0.01 then -- 打滑
        local rate = abs(m.vx) >= 1.75 and SKID_RUN or SKID_WALK
        if abs(m.vx) <= rate then m.vx = 0 else m.vx = m.vx - rate * press end
        m.face = press
        m.skid = abs(m.vx) > 0.7
      else
        m.skid = false
        local maxs, rate
        if run or (m.grace and m.grace > 0) then
          maxs, rate = MAX_RUN, ACC_RUN
        else
          maxs, rate = MAX_WALK, ACC_WALK
        end
        m.vx = m.vx + rate * press
        if abs(m.vx) > maxs then m.vx = maxs * press end
        m.face = press
      end
    else
      m.skid = false
      if m.vx ~= 0 then
        local rate = abs(m.vx) >= 1.75 and DEC_RUN or ACC_WALK
        if abs(m.vx) <= rate then m.vx = 0 else m.vx = m.vx - rate * sgn(m.vx) end
      end
    end
  else
    m.skid = false
    if press ~= 0 then
      local maxs, rate
      if abs(m.vx) >= 1.5625 or run then
        maxs, rate = MAX_RUN, ACC_RUN
      else
        maxs, rate = MAX_WALK, ACC_WALK
      end
      if abs(m.vx) < maxs then
        m.vx = m.vx + rate * press
        if abs(m.vx) > maxs then m.vx = maxs * press end
      end
      m.face = press
    end
  end
  -- 跳跃
  if m.on_ground and btnp(KEY.A) and not m.crouch then
    m.jgroup = jump_group(m.vx)
    m.vy = (m.jgroup >= 4) and JUMP_V0_F or JUMP_V0_S
    m.on_ground = false
    m.jumping = true
    sfx(m.big > 0 and FX.JUMPB or FX.JUMP)
  end
  -- 重力（按住跳较轻；松键或下落用重重力）
  if not m.on_ground then
    local g
    if m.vy < 0 and m.jumping and btn(KEY.A) then
      g = GRAV_RISE[m.jgroup]
    else
      m.jumping = false
      g = GRAV_FALL[m.jgroup or 1]
    end
    m.vy = m.vy + g
    if m.vy > MAX_FALL then m.vy = MAX_FALL end
  end
  -- 火球
  if m.big > 1 and btnp(KEY.B) then
    local n = 0
    for _, e in ipairs(game.ents) do if e.kind == "fb" then n = n + 1 end end
    if n < 2 then
      spawn_ent({ kind = "fb", x = m.x + m.face * 8, y = m.y + 8,
        vx = FIRE_VX * m.face, vy = 1, t = 0 })
      sfx(FX.FIRE)
    end
  end
  mario_tile_collide(m)
  if m.on_plat then m.y = m.y + m.on_plat.dy end
  -- 掉坑 / 触岩浆
  if m.y > 280 then
    game.state = "dying" game.st = 0
    music(MUS.DIE, 60, 240)
    return
  end
  -- 无敌星 / 受伤计时
  if m.star > 0 then
    m.star = m.star - 1
    if m.star == 0 and game.state == "play" and game.music_on then
      play_music()  -- 星星曲结束，恢复主曲
    end
  end
  if m.invuln > 0 then m.invuln = m.invuln - 1 end
  -- 行走动画
  local spd = abs(m.vx)
  local rate = spd >= 1.75 and 3 or (spd >= 0.875 and 5 or 8)
  if spd > 0.05 and m.on_ground then
    m.anim_t = (m.anim_t or 0) + 1
    if m.anim_t >= rate then m.anim_t = 0 m.anim_f = ((m.anim_f or 0) + 1) % 3 end
  elseif not m.on_ground then
    m.anim_f = nil
  else
    m.anim_t = nil m.anim_f = nil
  end
  -- 镜头推进（只向前；1-4 结局房间滚动锁）
  local target = m.x - 108
  local cammax = game.lv.w * 16 - 256
  if game.lv.princess then
    -- 滚动锁（原版 scrollLock）：公主房间完整入画后镜头停住
    cammax = min(cammax, game.lv.princess * 16 + 16 - 256)
  end
  if target > game.cam then game.cam = min(target, cammax) end
end

-- ---------------------------------------------------------------- 实体更新

local function ent_tile_side(e)
  -- 敌人贴墙反向；返回是否撞墙
  local hw = e.w / 2
  local dir = e.vx > 0 and 1 or -1
  local edge = e.x + dir * hw
  if solid_px(edge, e.y + 4) or solid_px(edge, e.y + (e.h or 14) - 2) then
    return true
  end
  return false
end

local function ent_gravity(e)
  e.vy = e.vy + E_GRAV
  if e.vy > E_FALLMAX then e.vy = E_FALLMAX end
  e.y = e.y + e.vy
  local h = e.h or 14
  if e.vy >= 0 and (solid_px(e.x - e.w / 2 + 1, e.y + h) or solid_px(e.x + e.w / 2 - 1, e.y + h)) then
    e.y = flr((e.y + h) / 16) * 16 - h
    e.vy = 0
    e.ground = true
  else
    e.ground = false
  end
end

local function spawn_enemies()
  local lv = game.lv
  for i, d in ipairs(lv.enemies or {}) do
    if not game.spawned[i] and d[1] * 16 < game.cam + 256 + 48 then
      game.spawned[i] = true
      if d[3] == "goomba" then
        spawn_ent({ kind = "goomba", x = d[1] * 16 + 8, y = d[2] * 16 - 14,
          vx = -E_WALK, vy = 0, w = 12, h = 14, t = 0 })
      elseif d[3] == "parakoopa" then
        spawn_ent({ kind = "parakoopa", x = d[1] * 16 + 8, y = d[2] * 16 - 20,
          vx = -E_WALK, vy = 0, w = 12, h = 20, t = 0 })
      else
        spawn_ent({ kind = "koopa", x = d[1] * 16 + 8, y = d[2] * 16 - 20,
          vx = -E_WALK, vy = 0, w = 12, h = 20, t = 0 })
      end
    end
  end
end

