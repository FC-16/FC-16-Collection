        e.y = e.y - 0.5
        e.rise = e.rise - 0.5
      end
    elseif e.kind == "star" then
      if e.rise and e.rise > 0 then
        e.y = e.y - 0.5
        e.rise = e.rise - 0.5
      else
        e.rise = nil
        e.x = e.x + e.vx
        if ent_tile_side(e) then e.vx = -e.vx e.x = e.x - e.vx end
        ent_gravity(e)
        if e.ground then e.vy = -4 end
