      if e.vy == 0 and e.y >= e.base + 40 then
        e.t = e.t + 1
        if e.t > 150 then e.t = 0 e.vy = -4.6 e.y = e.base + 48 sfx(FX.FIRE) end
      else
        e.vy = e.vy + 0.13
        e.y = e.y + e.vy
        if e.vy > 0 and e.y > e.base + 56 then
          e.y = e.base + 48 e.vy = 0 e.t = 0
        end
      end
      if abs(e.x - m.x) < 12 and e.y + 14 > my1 and e.y < my1 + mh
        and m.invuln <= 0 then
        hurt_mario()
      end
    elseif e.kind == "bflame" or e.kind == "bfire" then
      e.x = e.x + e.vx
      e.t = e.t + 1
      if e.kind == "bflame" then e.y = e.y + sin(e.t / 16) * 0.6 end
      if e.x < game.cam - 48 then dead = true end
      if abs(e.x - m.x) < 12 and e.y + 8 > my1 and e.y < my1 + mh
        and m.invuln <= 0 then
        hurt_mario()
      end
    elseif e.kind == "bowser" then
      local bridge_y = (game.lv.bridge and game.lv.bridge[3] or 9) * 16
      if e.dead then
        -- 被击破 / 断桥坠落
        e.vy = e.vy + 0.22
        e.y = e.y + e.vy
        if e.y > 300 then dead = true end
      else
        -- 沿桥面向马里奥移动（原版速度档 2，跳跃与喷火间隔固定）
        e.face = (m.x < e.x) and -1 or 1
        e.x = e.x + 0.3 * e.face
        e.hop_t = e.hop_t - 1
        if e.hop_t <= 0 and e.y >= bridge_y - 32 then
          e.vy = -3.6
          e.hop_t = 130 + flr(rnd(60))
        end
        if e.vy ~= 0 or e.y < bridge_y - 32 then
          e.vy = e.vy + 0.22
          e.y = min(e.y + e.vy, bridge_y - 32)
          if e.y >= bridge_y - 32 then e.vy = 0 end
        end
        e.fire_t = e.fire_t - 1
        if e.fire_t <= 0 and abs(m.x - e.x) < 200 then
          e.fire_t = 160 + flr(rnd(80))
          spawn_ent({ kind = "bfire", x = e.x + e.face * 14, y = e.y + 12,
            vx = 2.1 * e.face, t = 0 })
          sfx(FX.FIRE)
        end
        if e.hurt > 0 then e.hurt = e.hurt - 1 end
        -- 与马里奥接触：踩头安全反弹，侧碰受伤（原版规则）
        if abs(e.x - m.x) < 22 and e.y + 28 > my1 and e.y < my1 + mh then
          if m.vy > 0 and (m.y + mh) - e.y < 14 then
            m.vy = STOMP_BOUNCE
            m.jumping = btn(KEY.A)
            m.on_ground = false
            sfx(FX.STOMP)
          elseif m.invuln <= 0 and m.star <= 0 then
            hurt_mario()
          elseif m.star > 0 then
            e.hp = 0
          end
        end
      end
    elseif e.kind == "axe" then
      -- 斧头：触碰即断桥（原版桥面从斧头侧逐格塌落）
      if abs(e.x - m.x) < 14 and abs(e.y - (m.y + mh / 2)) < 20 then
        dead = true
        game.state = "bridge" game.st = 0
        game.bridge_k = 0
        add_score(5000)
        music(-1)
      end
    elseif e.kind == "princess" then
      e.t = e.t + 1
    end
    -- 道具拾取
    if not dead and (e.kind == "mush" or e.kind == "flower" or e.kind == "star" or e.kind == "oneup") then
      if abs(e.x - m.x) < (12 + mw) / 2 and e.y + 16 > my1 and e.y < my1 + mh then
        dead = true
        if e.kind == "mush" then
          add_score(1000) add_pop(e.x, e.y, "1000")
          sfx(FX.POWER)
          if m.big == 0 then
            m.big = 1 m.y = m.y - 15
            game.state = "grow" game.st = 0
          end
        elseif e.kind == "flower" then
          add_score(1000) add_pop(e.x, e.y, "1000")
          sfx(FX.POWER)
          if m.big == 0 then
            m.big = 1 m.y = m.y - 15
            game.state = "grow" game.st = 0
          elseif m.big == 1 then
            m.big = 2
            game.state = "grow" game.st = 0
          end
        elseif e.kind == "star" then
          add_score(1000) add_pop(e.x, e.y, "1000")
          m.star = STAR_TIME
          sfx(FX.POWER)
          if game.music_on then music(MUS.STAR, 100, 240) end
        else
          game.lives = game.lives + 1
          add_pop(e.x, e.y, "1UP")
          sfx(FX.ONEUP)
        end
      end
    end
    if not dead and (e.kind == "goomba" or e.kind == "koopa"
      or e.kind == "parakoopa" or e.kind == "shell") then
      -- 玩家与敌人（已扁的 goomba 不再判定）
      if not (e.kind == "goomba" and e.flat)
        and abs(e.x - m.x) < (12 + mw) / 2
        and e.y + (e.h or 14) > my1 and e.y < my1 + mh then
        if m.star > 0 then
          flip_kill(e, e.kind == "goomba" and 100 or 200, e.x, e.y)
        elseif m.vy > 0 and (m.y + mh) - e.y < 10 then
          -- 踩
          if e.kind == "goomba" then
            e.flat = true e.flat_t = e.t e.vx = 0
            sfx(FX.STOMP)
            chain_score(e.x, e.y)
          elseif e.kind == "koopa" or e.kind == "parakoopa" then
            e.kind = "shell" e.h = 14 e.y = e.y + 6 e.vx = 0 e.wake = SHELL_WAKE
            sfx(FX.STOMP)
            chain_score(e.x, e.y)
          elseif e.kind == "shell" then
            if e.vx == 0 then
              e.vx = (m.x < e.x) and SHELL_SPD or -SHELL_SPD
              e.chain = 0
              sfx(FX.KICK)
              add_score(400) add_pop(e.x, e.y, "400")
            else
              e.vx = 0
              e.wake = SHELL_WAKE
              sfx(FX.STOMP)
              chain_score(e.x, e.y)
            end
          end
          m.vy = STOMP_BOUNCE
          m.jumping = btn(KEY.A)
          m.jgroup = jump_group(m.vx)
          m.on_ground = false
        else
          if e.kind == "shell" and e.vx == 0 then
            e.vx = (m.x < e.x) and SHELL_SPD or -SHELL_SPD
            e.chain = 0
            sfx(FX.KICK)
            add_score(400) add_pop(e.x, e.y, "400")
          elseif m.invuln <= 0 then
            hurt_mario()
          end
        end
      end
    end
    if dead then table.remove(game.ents, i) end
  end
  -- 分数飘字
  for i = #game.pops, 1, -1 do
    local p = game.pops[i]
    p.t = p.t + 1
    p.y = p.y - 0.5
    if p.t > 40 then table.remove(game.pops, i) end
  end
end

-- ---------------------------------------------------------------- 关卡装载

local function make_mario(x, y, big)
  return { x = x, y = y, vx = 0, vy = 0, face = 1, big = big or 0,
    on_ground = false, crouch = false, jumping = false, jgroup = 1,
    anim_t = 0, anim_f = 0, star = 0, invuln = 0, grace = 0, skid = false }
end

-- 装载关卡：fresh = 重建地图与实体；否则复用既有运行态（奖励房往返）
local function load_level(lv, fresh, mx, my)
  game.lv = lv
  local rt = game.rt[lv]
  if fresh or rt == nil then
    rt = {
      contents = build_level(lv),
      spawned = {}, multi = {}, ents = {}, pops = {}, bumps = {},
    }
    game.rt[lv] = rt
    for _, p in ipairs(lv.plats or {}) do
      rt.ents[#rt.ents + 1] = { kind = "plat", x = p[1] * 16 + 8,
        cy = p[2] * 16, y = p[2] * 16, amp = p[3] * 16, dy = 0, dx = 0, t = flr(rnd(60)) }
    end
    -- 1-3 / 1-4 新增实体（升降平台、火棒、火柱、龙火、库巴、斧头、公主）
    for _, d in ipairs(lv.ents or {}) do
      local tx, ty, kind = d[1], d[2], d[3]
      if kind == "liftv" or kind == "lifth" then
        rt.ents[#rt.ents + 1] = { kind = "plat", axis = (kind == "liftv") and "v" or "h",
          x = tx * 16 + 8, cx = tx * 16 + 8, cy = ty * 16,
          y = ty * 16, amp = 32, dy = 0, dx = 0, t = (kind == "liftv") and 0 or 40 }
      elseif kind == "fire" then
        rt.ents[#rt.ents + 1] = { kind = "firebar", x = tx * 16 + 8, y = ty * 16 + 8,
          ang = flr(rnd(32)), spd = (d[4] == 0) and 56 or 40, dir = d[5] or -1, t = 0 }
      elseif kind == "podo" then
        rt.ents[#rt.ents + 1] = { kind = "podo", x = tx * 16 + 8, base = ty * 16,
          y = ty * 16 + 40, vy = 0, t = flr(rnd(160)) }
      elseif kind == "bflame" then
        rt.ents[#rt.ents + 1] = { kind = "bflame", x = tx * 16, y = ty * 16,
          vx = -1.3, t = 0 }
      end
    end
    if lv.bowser then
      rt.ents[#rt.ents + 1] = { kind = "bowser", x = lv.bowser * 16,
        y = (lv.bridge and lv.bridge[3] or 9) * 16 - 32,
        vx = 0, vy = 0, hp = 5, hurt = 0, fire_t = 150, hop_t = 100,
        face = -1, dead = false, w = 24, h = 30, t = 0 }
    end
    if lv.axe then
      rt.ents[#rt.ents + 1] = { kind = "axe", x = lv.axe[1] * 16 + 8,
        y = lv.axe[2] * 16 + 8, t = 0 }
    end
    if lv.princess then
      rt.ents[#rt.ents + 1] = { kind = "princess", x = lv.princess * 16 + 8,
        y = 12 * 16 - 32, t = 0 }
    end
  end
  game.contents = rt.contents
  game.spawned = rt.spawned
  game.multi = rt.multi
  game.ents = rt.ents
  game.pops = rt.pops
  game.bumps = rt.bumps
  if mx then
    game.mario = make_mario(mx, my, game.mario and game.mario.big or 0)
    if game.mario.big > 0 then game.mario.y = my - 30 end
  end
  game.cam = mid(game.mario.x - 108, 0, lv.w * 16 - 256)
  game.cam = max(game.cam, 0)
  if lv.time and lv.time > 0 then
    game.time = lv.time
    game.hurry = false
  end
  game.flag_y = nil
  game.chain = 0
end

local function level_music()
  local lv = game.lv
  if lv == nil then return MUS.GROUND end
  if lv.dungeon then return MUS.CASTLE end
  if lv.under then return MUS.UNDER end
  return MUS.GROUND
end

local function play_music()
  if not game.music_on then return end
  music(level_music(), 400, 240)
end

-- ---------------------------------------------------------------- 状态机

local function start_game()
  game.score = 0 game.coins = 0 game.lives = 3 game.lvi = 1
  game.rt = {}
  game.state = "inter" game.st = 0
  music(-1)
end

local function begin_play()
  local lv = LEVELS[game.lvi]
  load_level(lv, true, lv.start_x, lv.start_y)
  if lv.drop_in then game.mario.y = -32 end
  game.state = "play" game.st = 0
  play_music()
end

local function next_level()
  if game.lvi < #LEVELS then
    game.lvi = game.lvi + 1
    if game.lvi > game.bestlv then
      game.bestlv = game.lvi
      dset(1, game.bestlv) fflush()
    end
    game.state = "inter" game.st = 0
  else
    game.state = "clear" game.st = 0
    music(-1)
    dset(0, game.best) dset(1, game.bestlv) fflush()
  end
end

local function mario_die_end()
  game.lives = game.lives - 1
  if game.lives <= 0 then
    game.state = "over" game.st = 0
    dset(0, game.best) fflush()
    if game.music_on then music(MUS.OVER, 60, 240) end
  else
    game.state = "inter" game.st = 0
  end
end

local function update_play()
  local m = game.mario
  local lv = game.lv
  -- 计时
  if lv.time and lv.time > 0 then
    game.timefr = game.timefr + 1
    if game.timefr >= TIME_TICK then
      game.timefr = 0
      game.time = game.time - 1
      if game.time == 100 and not game.hurry then
        game.hurry = true
        -- 原版「时间告急」警号（TimeRunOutMusData）；播完恢复主曲
        -- （原版随后会整体提速主曲，本作简化为原速恢复，见 README 实现说明）
        if game.music_on then
          music(MUS.WARN, 60, 240)
          game.warn_t = 280
        end
      elseif game.time <= 0 then
        game.time = 0
        game.state = "dying" game.st = 0
        music(MUS.DIE, 60, 240)
        return
      end
    end
  end
  if game.warn_t then
    game.warn_t = game.warn_t - 1
    if game.warn_t <= 0 then
      game.warn_t = nil
      if game.music_on and game.state == "play" then play_music() end
    end
  end
  update_mario()
  if game.state ~= "play" then return end
  spawn_enemies()
  spawn_coins()
  update_ents()
  update_bumps()
  if game.shake > 0 then game.shake = game.shake - 1 end
  -- 旗杆
  if lv.flag and m.x >= lv.flag * 16 - 2 and game.state == "play" then
    local fy = m.y
    local pts = 100
    if fy <= 24 then pts = 5000
    elseif fy <= 34 then pts = 2000
    elseif fy <= 80 then pts = 800
    elseif fy <= 104 then pts = 400 end
    add_score(pts)
    add_pop(lv.flag * 16 + 16, fy, "" .. pts)
    m.x = lv.flag * 16 + 8
    m.vx = 0 m.vy = 0
    m.face = 1
    game.state = "flag" game.st = 0
    game.flag_y = 40
    music(-1)
    sfx(FX.FLAG)
    return
  end
  -- 进管道（站在可进管道顶按 ↓）
  if m.on_ground and btn(KEY.D) and not game.warp_used then
    local ftx = flr(m.x / 16)
    for _, p in ipairs(lv.pipes or {}) do
      if p[3] and (ftx == p[1] or ftx == p[1] + 1)
        and m.y + (m.big > 0 and 30 or 15) >= (12 - p[2]) * 16
        and m.y + (m.big > 0 and 30 or 15) <= (12 - p[2]) * 16 + 4 then
        game.state = "pipe" game.st = 0
        game.pipe_to = "bonus"
        game.warp_used = true
        sfx(FX.PIPE)
        music(-1)
        return
      end
    end
  end
  -- 奖励房出口
  if lv.bonus and m.on_ground and m.x >= lv.exit_pipe * 16 then
    game.state = "pipe" game.st = 0
    game.pipe_to = "main"
    sfx(FX.PIPE)
    music(-1)
    return
  end
end

local function update_states()
  local m = game.mario
  game.st = game.st + 1
  local st = game.state
  if st == "play" then
    if btnp(KEY.STA) then
      game.state = "pause" sfx(FX.PAUSE) music(-1, 200)
    elseif btnp(KEY.SEL) then
      game.music_on = not game.music_on
      dset(2, game.music_on and 0 or 1)
      if game.music_on then play_music() else music(-1, 200) end
    else
      update_play()
    end
  elseif st == "pause" then
    if btnp(KEY.STA) or btnp(KEY.A) then
      game.state = "play" sfx(FX.PAUSE)
      play_music()
    end
  elseif st == "inter" then
    if game.st > 120 then begin_play() end
  elseif st == "dying" then
    if game.st == 30 then m.vy = -4 end
    if game.st > 30 then
      m.vy = m.vy + 0.21875
      m.y = m.y + m.vy
    end
    if game.st > 210 then mario_die_end() end
  elseif st == "grow" or st == "shrink" then
    if game.st >= 48 then game.state = "play" end
  elseif st == "pipe" then
    if game.pipe_to == "bonus" then
      m.y = m.y + 1.5
      if game.st >= 32 then
        load_level(LEVEL_BONUS, true, 40, -24)
        game.state = "play"
        play_music()
      end
    else
      m.x = m.x + 1.5
      if game.st >= 32 then
        -- 从 1-1 出口管（t163）冒出
        load_level(LEVELS[game.lvi], false, 163 * 16 + 16, (12 - 2) * 16)
        game.mario.y = (12 - 2) * 16 - (game.mario.big > 0 and 30 or 15) + 8
        game.state = "pipeup" game.st = 0
      end
    end
  elseif st == "pipeup" then
    local h = game.mario.big > 0 and 30 or 15
    game.mario.y = game.mario.y - 1
    if game.mario.y <= (12 - 2) * 16 - h then
      game.mario.y = (12 - 2) * 16 - h
      game.state = "play"
      play_music()
    end
  elseif st == "flag" then
    m.y = m.y + 2
    game.flag_y = min((game.flag_y or 40) + 2, 160)
    local h = m.big > 0 and 30 or 15
    if m.y >= 176 - h then
      m.y = 176 - h
      if game.flag_y >= 160 then
        game.state = "flaghop" game.st = 0
        m.vy = -3 m.vx = 1.2
      end
    end
  elseif st == "flaghop" then
    m.vy = m.vy + GRAV_FALL[1]
    m.x = m.x + m.vx
    m.y = m.y + m.vy
    local h = m.big > 0 and 30 or 15
    if m.vy > 0 and solid_px(m.x - 4, m.y + h) then
      m.y = flr((m.y + h) / 16) * 16 - h
      m.vy = 0
      game.state = "walk" game.st = 0
      m.face = 1
    end
  elseif st == "walk" then
    m.vx = 1.2
    m.x = m.x + m.vx
    m.vy = m.vy + GRAV_FALL[1]
    if m.vy > MAX_FALL then m.vy = MAX_FALL end
    m.y = m.y + m.vy
    local h = m.big > 0 and 30 or 15
    if m.vy >= 0 and solid_px(m.x, m.y + h) then
      m.y = flr((m.y + h) / 16) * 16 - h
      m.vy = 0
    end
    if game.lv.castle and m.x >= game.lv.castle * 16 + 2 * 16 + 4 then
      game.state = "count" game.st = 0
    end
    -- 1-4：走到公主处触发结局（原版自动行走 → THANK YOU MARIO）
    if game.lv.princess and m.x >= game.lv.princess * 16 + 4 then
      game.state = "rescue" game.st = 0
      music(MUS.RESCUE, 400, 240)
    end
  elseif st == "bridge" then
    -- 断桥演出：从斧头侧逐格塌落，库巴坠入岩浆后自动向右走
    if game.st % 3 == 0 then
      local lv = game.lv
      local k = game.bridge_k
      if k < 13 then
        local tx = lv.bridge[2] - k
        mset(tx, lv.strip + lv.bridge[3], T.EMPTY)
        spawn_chunks(tx, lv.bridge[3])
        game.bridge_k = k + 1
        if game.st % 6 == 0 then sfx(FX.BREAK) end
        -- 库巴脚下的桥塌了 → 坠落
        for _, e in ipairs(game.ents) do
          if e.kind == "bowser" and not e.dead
            and tx * 16 + 8 > e.x - 12 and tx * 16 + 8 < e.x + 12 then
            e.dead = true
            e.vy = -2
            sfx(FX.STOMP)
          end
        end
      end
    end
    m.vx = 0
    if game.st > 100 then
      game.state = "walk" game.st = 0
    end
  elseif st == "rescue" then
    -- 救出公主：原版「城堡过关」 fanfare + 烟花，随后通关
    if game.st % 40 == 0 and game.st < 320 then
      for i = 1, 12 do
        local a = i / 12
        game.parts[#game.parts + 1] = {
          x = m.x - 128 + rnd(256), y = 40 + rnd(80),
          vx = cos(a) * 1.5, vy = sin(a) * 1.5, life = 30,
          c = ({ 30, 43, 59 })[flr(rnd(3)) + 1] }
      end
    end
    for i = #game.parts, 1, -1 do
      local p2 = game.parts[i]
      p2.x = p2.x + p2.vx p2.y = p2.y + p2.vy p2.life = p2.life - 1
      if p2.life <= 0 then table.remove(game.parts, i) end
    end
    if game.st > 400 then
      game.st2 = nil
      next_level()
    end
  elseif st == "count" then
    local done = true
    if game.time > 0 then
      local step = game.time > 2 and 2 or game.time -- 整数步进
      game.time = game.time - step
      add_score(step * 50)
      if game.st % 6 == 0 then sfx(FX.TICK) end
      done = false
    end
    if done then
      if game.st2 == nil then
        game.st2 = 0
        if game.music_on then music(MUS.WIN, 60, 240) end
      end
      game.st2 = game.st2 + 1
      if game.st2 > 110 then
        game.st2 = nil
        next_level()
      end
    end
  elseif st == "over" then
    if game.st > 40 and btnp(KEY.A) then
      game.score = 0 game.lives = 3
      game.state = "inter" game.st = 0
    elseif game.st > 40 and btnp(KEY.B) then
      game.state = "title" game.st = 0
    end
  elseif st == "clear" then
    if game.st > 60 and btnp(KEY.A) then
      game.state = "title" game.st = 0
    end
  elseif st == "title" then
    if btnp(KEY.A) then start_game() end
    if btnp(KEY.SEL) then
      game.music_on = not game.music_on
      dset(2, game.music_on and 0 or 1)
      if game.music_on then music(0, 500, 240) else music(-1, 200) end
    end
  end
end

