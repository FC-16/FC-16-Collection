local function draw_ent(e)
  local x, y = flr(e.x - 8), flr(e.y)
  if e.kind == "goomba" then
    if e.flat then
      spr(S.GOOMBA_FLAT, x, y)
    else
      spr(flr(e.t / 8) % 2 == 0 and S.GOOMBA or S.GOOMBA2, x, y)
    end
  elseif e.kind == "koopa" then
    local f = flr(e.t / 8) % 2
    spr(S.KOOPA_T + f, x, y, 1, 1, e.vx > 0)
    spr(S.KOOPA_B + f, x, y + 16, 1, 1, e.vx > 0)
  elseif e.kind == "shell" then
    if e.vx ~= 0 then
      spr(flr(e.t / 3) % 2 == 0 and S.SHELL or S.SHELL_W, x, y)
    elseif e.wake and e.wake < 90 and flr(e.t / 6) % 2 == 0 then
      spr(S.SHELL_W, x, y)
    else
      spr(S.SHELL, x, y)
    end
  elseif e.kind == "flip" then
    -- 翻面坠落：按原类型倒置绘制
    if e.fk == "koopa" or e.fk == "parakoopa" then
      spr(S.KOOPA_T, x, y, 1, 1, true, true)
      spr(S.KOOPA_B, x, y + 16, 1, 1, true, true)
    elseif e.fk == "shell" then
      spr(S.SHELL, x, y, 1, 1, false, true)
    else
      spr(S.GOOMBA, x, y, 1, 1, false, true)
    end
  elseif e.kind == "mush" then
    spr(S.MUSH, x, y)
  elseif e.kind == "oneup" then
    pal(C.RED, C.GREEN) pal(C.REDD, C.GREEND)
    spr(S.MUSH, x, y)
    pal(C.RED, C.RED) pal(C.REDD, C.REDD)
  elseif e.kind == "flower" then
    spr(S.FLOWER, x, y)
  elseif e.kind == "star" then
    spr(S.STAR, x, y)
  elseif e.kind == "coinp" or e.kind == "coin" then
    spr(S.COIN + flr(e.t / 6) % 4, x, y)
  elseif e.kind == "chunk" then
    spr(S.CHUNK, x, y)
  elseif e.kind == "fb" then
    spr(flr(e.t / 4) % 2 == 0 and S.FIRE or S.FIRE2, x, y)
  elseif e.kind == "boom" then
    spr(S.BOOM, x, y)
  elseif e.kind == "plat" then
    rectfill(flr(e.x) - 24, flr(e.y), 48, 8, C.GREENL)
    rectfill(flr(e.x) - 24, flr(e.y), 48, 2, C.GREEN)
    for i = -1, 1 do pset(flr(e.x) + i * 16, flr(e.y) + 5, C.GREEND) end
  elseif e.kind == "firebar" then
    -- 火棒：中心 + 5 颗火球沿 1/32 圈步进旋转（原版 FirebarObj）
    for i = 0, 5 do
      local bx, by = flr(e.x + cos(e.ang / 32) * i * 8), flr(e.y + sin(e.ang / 32) * i * 8)
      circfill(bx, by, 3, C.RED)
      circfill(bx, by, 1, C.QD)
    end
  elseif e.kind == "podo" then
    spr(S.PODO, x, y, 1, 1, false, e.vy > 0)
  elseif e.kind == "bflame" or e.kind == "bfire" then
    if e.vx > 0 then
      spr(S.BFLAME, x, y, 1, 1, true)
    else
      spr(S.BFLAME, x, y)
    end
  elseif e.kind == "bowser" then
    -- 32x32：左半 tile0/1，右半 tile2/3；受击闪烁
    if not (e.hurt > 0 and flr(e.hurt / 4) % 2 == 0) then
      local f = (flr(e.t / 12) % 2 == 0) and 0 or 4
      if e.dead then
        spr(S.BOWSER + f, x, y, 1, 1, false, true)
        spr(S.BOWSER + f + 1, x, y + 16, 1, 1, false, true)
      elseif e.face < 0 then
        spr(S.BOWSER + f, x, y)
        spr(S.BOWSER + f + 1, x, y + 16)
      else
        spr(S.BOWSER + f + 2, x, y)
        spr(S.BOWSER + f + 3, x, y + 16)
      end
    end
  elseif e.kind == "axe" then
    spr(S.AXE, x - 8, y - 8)
  elseif e.kind == "princess" then
    spr(S.PEACH, x - 8, y)
    spr(S.PEACH + 1, x - 8, y + 16)
  end
end

local STAR_FLASH = { { 43, 30 }, { 44, 31 }, { 46, 29 }, { 30, 43 } }

local function draw_mario()
  local m = game.mario
  if game.state == "count" or game.state == "clear" then return end
  if m.invuln > 0 and game.state == "play" and flr(m.invuln / 4) % 2 == 1 then return end
  local x = flr(m.x - 8)
  local y = flr(m.y)
  local frame
  local growing = game.state == "grow" or game.state == "shrink"
  local big = m.big
  if growing then
    big = flr(game.st / 6) % 2 == 0 and m.big or (m.big > 0 and 0 or 1)
    if game.state == "grow" and m.big == 2 then big = flr(game.st / 6) % 2 == 0 and 1 or 2 end
  end
  if game.state == "dying" then
    spr(S.MS_DEAD, x, y)
    return
  end
  local fh = m.face < 0
  if big == 0 then
    if game.state == "flag" then
      frame = S.MS_JUMP
    elseif not m.on_ground then
      frame = S.MS_JUMP
    elseif m.skid then
      frame = S.MS_SKID
    elseif m.crouch then
      frame = S.MS_STAND
    elseif m.anim_f then
      frame = S.MS_W1 + m.anim_f
    else
      frame = S.MS_STAND
    end
    spr(frame, x, y, 1, 1, fh)
  else
    local top
    if m.crouch then
      spr(S.MB_CROUCH, x, y, 1, 1, fh)
      top = nil
    elseif game.state == "flag" then
      top = S.MB_TOP + 4
    elseif not m.on_ground then
      top = S.MB_TOP + 4
    elseif m.skid then
      top = S.MB_TOP + 5
    elseif m.anim_f then
      top = S.MB_TOP + m.anim_f
    else
      top = S.MB_TOP
    end
    if top then
      if m.big == 2 then
        pal(C.RED, C.WHITE) pal(C.BLUE, C.RED)
      end
      if m.star > 0 then
        local f = STAR_FLASH[flr(frame() / 4) % 4 + 1]
        pal(C.RED, f[1]) pal(C.BLUE, f[2])
      end
      spr(top, x, y, 1, 1, fh)
      spr(S.MB_BOT + (top - S.MB_TOP), x, y + 16, 1, 1, fh)
      if m.big == 2 then
        pal(C.RED, C.RED) pal(C.BLUE, C.BLUE)
      end
      if m.star > 0 then
        pal(C.RED, C.RED) pal(C.BLUE, C.BLUE)
      end
    end
  end
end

