  local k = game.contents[tx .. "," .. ty]
  return k == "H" or k == "HC"
end

local function solid_or_hidden(tx, ty, up)
  if fget(tile_at(tx, ty), 0) then return true end
  return up and hidden_at(tx, ty)
end

