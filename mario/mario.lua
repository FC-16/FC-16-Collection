-- ---------------------------------------------------------------- 物理换算表（README 同步）
-- 参考实现（亚像素 1/256 px，60fps）        换算        本作（px/帧 或 px/帧^2）
-- MAX_WALK_SPEED      0x18/16            = 1.5        最大步行
-- MAX_RUN_SPEED       0x28/16            = 2.5        最大跑动
-- WALK_ACCEL          0x98/256           = 0.40625    步行加速 / 低速松键减速
-- RUN_ACCEL           0xe4/256           = 0.109375   按住 B 同向加速
-- RELEASE_DECEL(高速) 0xd0/256           = 0.1875     高速段松键减速 / 空中快档加速
-- SKID_DECEL          2 x 上述两档        = 0.8125 / 0.375  反向打滑
-- JUMP_V0             -4 / -5 px/f       按水平速度五档
-- RISE_GRAVITY        $20 $20 $1e $28 $28 → 0.125 / 0.125 / 0.1171875 / 0.15625 / 0.15625
-- FALL_GRAVITY        $70 $70 $60 $90 $90 → 0.4375 / 0.4375 / 0.375 / 0.5625 / 0.5625
-- MAX_FALL            4 + frac<0x80      ≈ 4.5
-- ENEMY_WALK          0x08/16            = 0.5
-- SHELL_SPEED         0x30/16            = 3.0
-- FIREBALL            0x40/16            = 4.0（重力 0x50/256=0.3125，反弹 -3）
-- STOMP_BOUNCE        $fc                = -4（按住 A 上升期间轻重力）
-- TIME_TICK           每 24 帧减 1（400 起倒计，剩 100 警告，归零死亡）
