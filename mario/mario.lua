        e.kind = "boom" e.t = 0
      end
      if e.kind == "fb" then
        for _, o in ipairs(game.ents) do
          if (o.kind == "goomba" or o.kind == "koopa" or o.kind == "parakoopa"
            or o.kind == "shell")
            and abs(o.x - e.x) < 12 and abs(o.y - e.y) < 16 then
