            o.hurt = 30
            e.kind = "boom" e.t = 0
            sfx(FX.KICK)
            if o.hp <= 0 then
              o.dead = true
              o.vy = -4
              add_score(5000)
            end
            break
          end
        end
      end
      if e.kind == "fb" and (e.x < game.cam - 16 or e.x > game.cam + 272 or e.y > 270) then
        dead = true
      end
    elseif e.kind == "boom" then
      if e.t > 10 then dead = true end
    elseif e.kind == "coin" then
