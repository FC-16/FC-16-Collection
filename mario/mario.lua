      e.vy = e.vy + 0.3125
      e.x = e.x + e.vx
      e.y = e.y + e.vy
      if e.y > 280 then dead = true end
    elseif e.kind == "fb" then
      e.x = e.x + e.vx
      e.vy = e.vy + FIRE_GRAV
      e.y = e.y + e.vy
      if e.vy > 0 and (solid_px(e.x, e.y + 6) or solid_px(e.x, e.y + 8)) then
        e.y = flr((e.y + 8) / 16) * 16 - 8
        e.vy = FIRE_BOUNCE
