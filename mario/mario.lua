-- ---------------------------------------------------------------- 关卡构建

local game -- 全局游戏状态（_init 内初始化）

local function tile_set(tx, ty, t) mset(tx, ty, t) end

-- 把关卡的块列表写入地图；返回 contents 表（"tx,ty" → 内容定义）
local BLOCK_TILE = { B = T.BRICK, Q = T.QMARK, P = T.QMARK, S = T.BRICK,
  M = T.BRICK, H = 0, HC = 0, U = T.USED }

local function build_level(lv)
  -- 清空该地图条带
  for ty = lv.strip, lv.strip + 15 do
    for tx = 0, 255 do mset(tx, ty, 0) end
  end
  -- 地面（两行）与深底
  for _, seg in ipairs(lv.ground) do
    for tx = seg[1], seg[2] do
      mset(tx, lv.strip + 12, lv.castle and T.CBRICK or T.GROUND)
      mset(tx, lv.strip + 13, lv.castle and T.CBRICK or T.GROUND)
      mset(tx, lv.strip + 14, T.GROUND)
      mset(tx, lv.strip + 15, T.GROUND)
    end
  end
  -- 城堡地形段（1-4：地板表面行 / 天花板深度 / 行8中梁；nil 地板 = 岩浆坑）
  if lv.terrain then
    for _, s in ipairs(lv.terrain) do
      local x0, x1, surf, ceil, mid = s[1], s[2], s[3], s[4], s[5]
      for tx = x0, x1 do
        if ceil and ceil > 0 then
          for r = 1, ceil do mset(tx, lv.strip + r, T.CBRICK) end
        end
        if mid then mset(tx, lv.strip + 8, T.CBRICK) end
        if surf then
          for r = surf, 15 do mset(tx, lv.strip + r, T.CBRICK) end
        else
          mset(tx, lv.strip + 12, T.LAVAT)
          mset(tx, lv.strip + 13, T.LAVAB)
        end
      end
    end
  end
  -- 结尾区顶部一行天花板（1-3 x154 起，原版 terrain=2）
  if lv.ceil1 then
    for _, seg in ipairs(lv.ceil1) do
      for tx = seg[1], seg[2] do mset(tx, lv.strip + 1, T.GROUND) end
    end
  end
  -- 天花板（地下）
  if lv.ceiling then
    for _, seg in ipairs(lv.ceiling) do
      for tx = seg[1], seg[2] do
        mset(tx, lv.strip + 2, T.BRICK)
        mset(tx, lv.strip + 1, T.BRICK)
      end
    end
  end
  -- 左墙（地下）
  if lv.wall then
    for ty = 1, 13 do mset(lv.wall, lv.strip + ty, T.BRICK) end
  end
  -- 树台（1-3：台面三段瓦 + 下方树干；树干为背景不参与碰撞）
  if lv.trees then
    for _, t in ipairs(lv.trees) do
      local tx, ty, w = t[1], t[2], t[3]
      mset(tx, lv.strip + ty, T.TREE_L)
      for i = 1, w - 2 do mset(tx + i, lv.strip + ty, T.TREE_M) end
      mset(tx + w - 1, lv.strip + ty, T.TREE_R)
      for r = ty + 1, 14 do
        if mget(tx + flr(w / 2), lv.strip + r) == T.EMPTY then
          mset(tx + flr(w / 2), lv.strip + r, T.TRUNK)
        end
      end
    end
  end
  -- 实心行（1-4 入口砖垛 / 火棒立柱）
  for _, s in ipairs(lv.solidrows or {}) do
    for i = 0, s[3] - 1 do mset(s[1] + i, lv.strip + s[2], T.CBRICK) end
  end
  -- 城堡桥与链节（1-4 Boss 段）
  if lv.bridge then
    for tx = lv.bridge[1], lv.bridge[2] do
      mset(tx, lv.strip + lv.bridge[3], T.BRIDGE)
    end
  end
  if lv.chain then
    mset(lv.chain[1], lv.strip + lv.chain[2], T.CHAIN)
  end
  -- 块与内容
  local contents = {}
  for _, b in ipairs(lv.blocks or {}) do
    local tx, ty, kind = b[1], b[2], b[3]
    if kind ~= "HC" then mset(tx, lv.strip + ty, BLOCK_TILE[kind]) end
    contents[tx .. "," .. ty] = kind
  end
  -- 管道
  for _, p in ipairs(lv.pipes or {}) do
    local tx, h = p[1], p[2]
    mset(tx, lv.strip + 12 - h, T.PIPE_TL)
    mset(tx + 1, lv.strip + 12 - h, T.PIPE_TR)
    for i = 1, h - 1 do
      mset(tx, lv.strip + 12 - h + i, T.PIPE_BL)
      mset(tx + 1, lv.strip + 12 - h + i, T.PIPE_BR)
    end
  end
  -- 上行阶梯（列高 1..n，n 重复一次）
  for _, s in ipairs(lv.stairs or {}) do
    local tx, n = s[1], s[2]
    for i = 0, n - 1 do
      local h = min(i + 1, n - 1)
      for r = 0, h - 1 do mset(tx + i, lv.strip + 11 - r, T.SOLID) end
    end
  end
  -- 独立实心柱
  for _, s in ipairs(lv.solidcols or {}) do
    for r = 0, s[2] - 1 do mset(s[1], lv.strip + 11 - r, T.SOLID) end
  end
  -- 旗杆（球 + 杆 + 底座）与城堡
  if lv.flag then
    local tx = lv.flag
    mset(tx, lv.strip + 2, T.BALL)
    for ty = 3, 10 do mset(tx, lv.strip + ty, T.POLE) end
    mset(tx, lv.strip + 11, T.SOLID)
    fset(T.POLE, 0, 0)
  end
  for _, cx in ipairs({ lv.castle2, lv.castle }) do
    if cx then
      for r = 0, 4 do
        for c = 0, 4 do
          local t = T.CASTLE
          if r >= 2 and c == 2 then t = T.CDOOR end
          if (r == 1 or r == 3) and (c == 1 or c == 3) then t = T.CWIN end
          mset(cx + c, lv.strip + 11 - r, t)
        end
      end
      for c = 0, 4 do mset(cx + c, lv.strip + 6, T.CTOP) end
      fset(T.CASTLE, 0, 0) fset(T.CWIN, 0, 0) fset(T.CDOOR, 0, 0) fset(T.CTOP, 0, 0)
    end
  end
  return contents
end

