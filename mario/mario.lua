-- bake_digits(id, map, rows)：逐像素把 16x16 点阵串写入瓦片 id
-- map 为「字符 → 全局色号」表，'.' 为透明（写 0）
local function bake_digits(id, map, rows)
  local base = id * 256
  for y = 0, 15 do
    local row = rows[y + 1] or ""
    for x = 0, 15 do
      local ch = row:sub(x + 1, x + 1)
      poke(base + y * 16 + x, ch == "." and 0 or (map[ch] or 0))
    end
  end
end

