-- 顶块：返回是否发生弹跳动画
local function bump_block(tx, ty)
  local key = tx .. "," .. ty
  local kind = game.contents[key]
  local m = game.mario
  -- 顶块震杀站在上面的敌人
  for _, e in ipairs(game.ents) do
    if e.kind == "goomba" or e.kind == "koopa" or e.kind == "parakoopa" or e.kind == "mush"
      or e.kind == "oneup" or e.kind == "star" or e.kind == "shell" then
      local ex, ey = e.x, e.y + (e.h or 14)
      if abs(ex - (tx * 16 + 8)) < 14 and abs(ey - ty * 16) < 4 then
        if e.kind == "mush" or e.kind == "oneup" or e.kind == "star" then
          e.vx = -e.vx e.vy = -3 -- 道具被弹起反向
        else
          flip_kill(e, 100, e.x, e.y)
        end
      end
    end
  end
  if kind == nil then
    sfx(FX.BUMP)
    return false
  end
  if kind == "Q" or kind == "HC" then
    game.contents[key] = nil
    mset(tx, game.lv.strip + ty, T.USED)
    spawn_coin_pop(tx, ty)
    add_coin()
    game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.USED }
  elseif kind == "P" then
    game.contents[key] = nil
    mset(tx, game.lv.strip + ty, T.USED)
    if m.big == 0 then
      spawn_item(tx, ty, "mush")
    else
      spawn_item(tx, ty, "flower")
    end
    game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.USED }
  elseif kind == "H" then
    game.contents[key] = nil
    mset(tx, game.lv.strip + ty, T.USED)
    spawn_item(tx, ty, "oneup")
    game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.USED }
  elseif kind == "S" then
    game.contents[key] = nil
    mset(tx, game.lv.strip + ty, T.USED)
    spawn_item(tx, ty, "star")
    game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.USED }
  elseif kind == "M" then
    spawn_coin_pop(tx, ty)
    add_coin()
    if game.multi[key] == nil then
      game.multi[key] = MULTI_COIN_T
      game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.BRICK }
    else
      game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.BRICK }
    end
  elseif kind == "B" then
    if m.big > 0 then
      game.contents[key] = nil
      mset(tx, game.lv.strip + ty, T.EMPTY)
      spawn_chunks(tx, ty)
      add_score(50)
      sfx(FX.BREAK)
      game.shake = 4
      return false
    end
    game.bumps[#game.bumps + 1] = { tx = tx, ty = ty, t = 0, tile = T.BRICK }
    sfx(FX.BUMP)
  else
    sfx(FX.BUMP)
    return false
  end
  return true
end

local function update_bumps()
  for i = #game.bumps, 1, -1 do
    local b = game.bumps[i]
    if b.t == 0 then mset(b.tx, game.lv.strip + b.ty, T.EMPTY) end
    b.t = b.t + 1
    if b.t >= 12 then
      mset(b.tx, game.lv.strip + b.ty, b.tile)
      table.remove(game.bumps, i)
    end
  end
  for key, t in pairs(game.multi) do
    if t <= 1 then
