local function add_pop(x, y, txt)
  game.pops[#game.pops + 1] = { x = x, y = y, txt = txt, t = 0 }
end

local function add_score(n)
  game.score = game.score + n
  if game.score > game.best then game.best = game.score end
end

local function add_coin(x, y)
  game.coins = game.coins + 1
  add_score(200)
  if x then add_pop(x, y, "200") end
  sfx(FX.COIN)
  if game.coins >= 100 then
    game.coins = game.coins - 100
    game.lives = game.lives + 1
    sfx(FX.ONEUP)
  end
end

-- 连踩计分：100 200 400 500 800 1000 2000 4000 5000 8000 之后 1UP
local CHAIN_PTS = { 100, 200, 400, 500, 800, 1000, 2000, 4000, 5000, 8000 }
local function chain_score(x, y)
  game.chain = game.chain + 1
  if game.chain > #CHAIN_PTS then
    game.lives = game.lives + 1
    add_pop(x, y, "1UP")
    sfx(FX.ONEUP)
  else
    local p = CHAIN_PTS[game.chain]
    add_score(p)
    add_pop(x, y, "" .. p)
  end
end

